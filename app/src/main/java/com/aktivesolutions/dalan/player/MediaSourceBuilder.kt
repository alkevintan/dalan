/**
 * Port of SmartTube's ExoMediaSourceFactory. Builds the ExoPlayer MediaSource for a
 * [MediaItemFormatInfo] following [SourceOrder]. Uses the built-in HttpURLConnection data source
 * (the OkHttp/Cronet ExoPlayer extensions are not vendored).
 */
class MediaSourceBuilder(private val context: Context) {

    private var mediaDataSourceFactory: DataSource.Factory? = null
    private var sabrDataSourceFactory: DataSource.Factory? = null

    /** Result of [build]. [source] is null for UNPLAYABLE / EMPTY. */
    class Built(val kind: SourceKind, val source: MediaSource?)

    fun build(f: MediaItemFormatInfo): Built {
        val kind = SourceOrder.choose(f)
        val source: MediaSource? = when (kind) {
            SourceKind.DASH_FORMATS -> try {
                fromDashFormatInfo(f)
            } catch (e: Exception) {
                // fall back to the MPD generated by youtubeapi
                f.createMpdStream()?.let { fromDashManifest(it) } ?: throw e
            }
            SourceKind.SABR -> fromSabrFormatInfo(f)
            SourceKind.DASH_URL -> fromDashManifestUrl(f.dashManifestUrl)
            SourceKind.HLS_URL -> fromHlsPlaylist(f.hlsManifestUrl)
            SourceKind.URL_LIST -> fromUrlList(f.createUrlList())
            SourceKind.UNPLAYABLE, SourceKind.EMPTY -> null
        }
        return Built(kind, source)
    }

    fun fromSabrFormatInfo(f: MediaItemFormatInfo): MediaSource =
        SabrMediaSource.Factory(sabrChunkSourceFactory(), null)
            .setLoadErrorHandlingPolicy(SabrDefaultLoadErrorHandlingPolicy())
            .createMediaSource(SabrManifestParser().parse(f))

    fun fromDashFormatInfo(f: MediaItemFormatInfo): MediaSource =
        DashMediaSource.Factory(dashChunkSourceFactory(), null)
            .setLoadErrorHandlingPolicy(DashDefaultLoadErrorHandlingPolicy())
            .createMediaSource(DashManifestParser2().parse(f))

    fun fromDashManifest(mpd: InputStream): MediaSource {
        val manifest = try {
            StaticDashManifestParser().parse(DASH_MANIFEST_URI, mpd)
        } catch (e: IOException) {
            throw IllegalStateException("Malformed mpd", e)
        }
        return DashMediaSource.Factory(dashChunkSourceFactory(), null)
            .setLoadErrorHandlingPolicy(DashDefaultLoadErrorHandlingPolicy())
            .createMediaSource(manifest)
    }

    @Suppress("DEPRECATION")
    fun fromDashManifestUrl(url: String): MediaSource =
        DashMediaSource.Factory(dashChunkSourceFactory(), mediaDataSourceFactory())
            .setManifestParser(LiveDashManifestParser()) // stateful: must be new for each live source
            .setLoadErrorHandlingPolicy(DashDefaultLoadErrorHandlingPolicy())
            .createMediaSource(Uri.parse(url))

    @Suppress("DEPRECATION")
    fun fromHlsPlaylist(url: String): MediaSource =
        HlsMediaSource.Factory(mediaDataSourceFactory()).createMediaSource(Uri.parse(url))

    @Suppress("DEPRECATION")
    fun fromUrlList(urls: List<String>): MediaSource =
        ExtractorMediaSource.Factory(mediaDataSourceFactory())
            .setExtractorsFactory(DefaultExtractorsFactory())
            .createMediaSource(Uri.parse(urls[0])) // item with max resolution

    /** Side-loads a WebVTT caption track and merges it with [main]. */
    @Suppress("DEPRECATION")
    fun withCaption(main: MediaSource, sub: MediaSubtitle, durationUs: Long): MediaSource {
        val url = sub.baseUrl ?: return main
        val format = Format.createTextSampleFormat(
            CAPTION_FORMAT_ID, MimeTypes.TEXT_VTT, C.SELECTION_FLAG_DEFAULT, sub.languageCode
        )
        val subSource = SingleSampleMediaSource.Factory(mediaDataSourceFactory())
            .createMediaSource(Uri.parse(url), format, if (durationUs > 0) durationUs else C.TIME_UNSET)
        return MergingMediaSource(main, subSource)
    }

    fun release() {
        mediaDataSourceFactory = null
        sabrDataSourceFactory = null
    }

    // --- data sources ---

    private fun buildDataSourceFactory(readTimeoutMs: Int): DataSource.Factory {
        val http = DefaultHttpDataSourceFactory(
            USER_AGENT, null, OkHttpManager.getConnectTimeoutMs().toInt(), readTimeoutMs, true
        )
        return DefaultDataSourceFactory(context, null, http)
    }

    private fun mediaDataSourceFactory(): DataSource.Factory =
        mediaDataSourceFactory ?: buildDataSourceFactory(OkHttpManager.getReadTimeoutMs().toInt()).also { mediaDataSourceFactory = it }

    /** SABR answers within milliseconds when healthy: fail fast so the chunk source can switch network. */
    private fun sabrMediaDataSourceFactory(): DataSource.Factory =
        sabrDataSourceFactory ?: buildDataSourceFactory(SABR_READ_TIMEOUT_MS).also { sabrDataSourceFactory = it }

    private fun sabrChunkSourceFactory(): SabrChunkSource.Factory =
        DefaultSabrChunkSource.Factory(sabrMediaDataSourceFactory(), MAX_SEGMENTS_PER_LOAD)

    private fun dashChunkSourceFactory(): DashChunkSource.Factory =
        DefaultDashChunkSource.Factory(mediaDataSourceFactory(), MAX_SEGMENTS_PER_LOAD)

    /** DASH manifest parser that forces a static (non-dynamic) manifest. EXO 2.10. */
    private class StaticDashManifestParser : DashManifestParser() {
        override fun buildMediaPresentationDescription(
            availabilityStartTime: Long, durationMs: Long, minBufferTimeMs: Long, dynamic: Boolean,
            minUpdateTimeMs: Long, timeShiftBufferDepthMs: Long, suggestedPresentationDelayMs: Long,
            publishTimeMs: Long, programInformation: ProgramInformation?, utcTiming: UtcTimingElement?,
            location: Uri?, periods: List<Period>,
        ): DashManifest = DashManifest(
            availabilityStartTime, durationMs, minBufferTimeMs, false, minUpdateTimeMs,
            timeShiftBufferDepthMs, suggestedPresentationDelayMs, publishTimeMs, programInformation,
            utcTiming, location, periods
        )
    }

    companion object {
        const val CAPTION_FORMAT_ID = "dalan-caption"
        private const val MAX_SEGMENTS_PER_LOAD = 1
        private const val SABR_READ_TIMEOUT_MS = 4_000
        private val USER_AGENT: String = DefaultHeaders.APP_USER_AGENT
        private val DASH_MANIFEST_URI: Uri = Uri.parse("https://example.com/test.mpd")
    }
}
